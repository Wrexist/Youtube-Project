/**
 * Put a Studio launcher where people actually look for one.
 *
 *   node scripts/install-shortcut.mjs
 *
 * Run automatically at the end of setup, and safe to run again — it overwrites
 * its own previous output and touches nothing else.
 *
 * What it makes, per platform:
 *
 *   Windows   %USERPROFILE%\Desktop\Studio.lnk  → Studio.cmd, with an icon
 *   macOS     ~/Applications/Studio.app         → a real bundle, no Terminal
 *   Linux     ~/.local/share/applications/…     → a .desktop entry, plus one on
 *                                                 the Desktop if there is one
 *
 * The point is that "open Studio" should be a thing you double-click, not a
 * command you remember. Everything here is a thin wrapper over `npm start --
 * --open`; none of it is a second way for the app to start, because two start
 * paths means one of them silently rots.
 */

import { chmodSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const HOME = homedir();

/** Where the Desktop is. Not always `~/Desktop` — localised on Windows, and
 *  absent entirely on a headless Linux box. */
function desktopDir() {
  if (process.platform === "win32") {
    // Ask the shell rather than guessing: on a Swedish install this is
    // "Skrivbord", on OneDrive-backed profiles it is somewhere else entirely,
    // and a hardcoded ~/Desktop silently writes to a folder nobody sees.
    const result = spawnSync(
      "powershell",
      ["-NoProfile", "-Command", "[Environment]::GetFolderPath('Desktop')"],
      { encoding: "utf8" },
    );
    const path = result.stdout?.trim();
    if (path && existsSync(path)) return path;
  }
  const fallback = join(HOME, "Desktop");
  return existsSync(fallback) ? fallback : null;
}

function windows() {
  const desktop = desktopDir();
  if (!desktop) return "no Desktop folder found — skipped";

  const target = join(ROOT, "Studio.cmd");
  const icon = join(ROOT, "assets", "studio.ico");
  const link = join(desktop, "Studio.lnk");

  // A .lnk is a binary format; the supported way to write one is the shell's own
  // COM object. Escaping matters — paths routinely contain spaces and
  // apostrophes ("C:\Users\Anne's PC\...").
  const q = (s) => `'${s.replace(/'/g, "''")}'`;
  const script = [
    `$s = (New-Object -ComObject WScript.Shell).CreateShortcut(${q(link)})`,
    `$s.TargetPath = ${q(target)}`,
    `$s.WorkingDirectory = ${q(ROOT)}`,
    `$s.Description = 'Studio — idea to published video'`,
    existsSync(icon) ? `$s.IconLocation = ${q(icon)}` : "",
    // Minimised: the console is how you stop Studio, so it has to exist, but it
    // is not what you want in your face when the browser is about to open.
    `$s.WindowStyle = 7`,
    `$s.Save()`,
  ]
    .filter(Boolean)
    .join("; ");

  const result = spawnSync("powershell", ["-NoProfile", "-Command", script], {
    encoding: "utf8",
  });
  if (result.status !== 0) {
    return `could not create the shortcut: ${(result.stderr || "").trim().split("\n")[0]}`;
  }
  return link;
}

function macos() {
  // A minimal .app bundle: a directory with a plist and an executable. Double
  // -clicking runs the executable with no Terminal window, which is the whole
  // difference between "a script" and "an app" as far as anyone using it cares.
  const app = join(HOME, "Applications", "Studio.app");
  const macOS = join(app, "Contents", "MacOS");
  mkdirSync(macOS, { recursive: true });

  writeFileSync(
    join(app, "Contents", "Info.plist"),
    `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Studio</string>
  <key>CFBundleDisplayName</key><string>Studio</string>
  <key>CFBundleIdentifier</key><string>com.studio.launcher</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>Studio</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
</dict>
</plist>
`,
  );

  const launcher = join(macOS, "Studio");
  writeFileSync(
    launcher,
    `#!/bin/bash
# Generated by scripts/install-shortcut.mjs. Re-run setup to refresh.
cd ${JSON.stringify(ROOT)} || exit 1

# A GUI-launched process inherits almost nothing: no shell profile, so no nvm,
# no Homebrew on Apple silicon. Without this, node is simply not found and the
# app dies silently with no window to say so.
export PATH="/opt/homebrew/bin:/usr/local/bin:$HOME/.nvm/versions/node/$(ls "$HOME/.nvm/versions/node" 2>/dev/null | tail -1)/bin:$PATH"

if ! command -v node >/dev/null 2>&1; then
  osascript -e 'display alert "Node.js not found" message "Studio needs Node.js. Install the LTS release from nodejs.org, then try again."'
  exit 1
fi

if [ ! -d node_modules ]; then
  osascript -e 'display alert "Studio is not installed yet" message "Run ./scripts/setup.sh in the Studio folder first. It takes a couple of minutes."'
  exit 1
fi

exec npm start -- --open
`,
  );
  chmodSync(launcher, 0o755);
  return app;
}

/** Quote a path for a .desktop `Exec=` value.
 *
 *  Exec is tokenised by the launcher, not handed to a shell, so an unquoted
 *  path under e.g. `~/My Projects/Studio` arrives as two arguments and the
 *  entry fails to start with no useful error. Two layers of escaping stack up:
 *  the Desktop Entry spec reserves `"`, backtick, `$` and `\` inside a quoted
 *  argument (each escaped with a backslash), and a backslash is *also* an
 *  escape character in a .desktop value — so every backslash the first layer
 *  produces has to be doubled again on the way to the file.
 *
 *  Only Exec needs this. Path= and Icon= take the whole line verbatim, and
 *  quoting them would make the quotes part of the value. */
function execQuote(path) {
  const escaped = path
    .replace(/\\/g, "\\\\\\\\") // literal \ → \\ (exec) → \\\\ (file)
    .replace(/(["`$])/g, "\\\\$1"); // literal " → \" (exec) → \\" (file)
  return `"${escaped}"`;
}

function linux() {
  const launcherPath = join(ROOT, "scripts", "studio-launch.sh");
  const entry = `[Desktop Entry]
Type=Application
Name=Studio
Comment=Idea to published video
Exec=${execQuote(launcherPath)}
Path=${ROOT}
Icon=${join(ROOT, "assets", "studio.png")}
Terminal=true
Categories=AudioVideo;Development;
`;

  // The launcher is its own file rather than an inline Exec= because the Exec
  // quoting rules above only get harder once there are arguments in the line.
  const launcher = launcherPath;
  writeFileSync(
    launcher,
    `#!/bin/bash
# Generated by scripts/install-shortcut.mjs.
cd ${JSON.stringify(ROOT)} || exit 1
exec npm start -- --open
`,
  );
  chmodSync(launcher, 0o755);

  const written = [];
  const apps = join(HOME, ".local", "share", "applications");
  mkdirSync(apps, { recursive: true });
  writeFileSync(join(apps, "studio.desktop"), entry);
  written.push(join(apps, "studio.desktop"));

  const desktop = desktopDir();
  if (desktop) {
    const path = join(desktop, "studio.desktop");
    writeFileSync(path, entry);
    // GNOME refuses to launch a .desktop that is not executable, and shows it as
    // a text file instead — which looks exactly like a broken install.
    chmodSync(path, 0o755);
    written.push(path);
  }
  return written.join(", ");
}

try {
  const where =
    process.platform === "win32"
      ? windows()
      : process.platform === "darwin"
        ? macos()
        : linux();
  console.log(`  Shortcut: ${where}`);
} catch (error) {
  // Never fatal. A missing shortcut is a small inconvenience; a setup script
  // that aborts over one, having already installed everything, is a much
  // bigger one.
  console.log(`  Shortcut: skipped (${error.message})`);
}
